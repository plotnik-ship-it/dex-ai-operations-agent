import {OllamaPlanner} from './ollama.js';
import {DemoPlanner} from './agent.js';
import {registerDemoWeb} from './web.js';
import {ApprovalService} from './approval.js';
import { Pool } from 'pg';
import { buildApp } from './app.js';
import { demoAuthenticator } from './auth.js';
import { PostgresOperationsStore } from './store.js';
if(process.env.DEMO_AUTH_ENABLED!=='true')throw new Error('Local demo requires DEMO_AUTH_ENABLED=true. Do not host this adapter.');
if(!process.env.DATABASE_URL)throw new Error('DATABASE_URL required');
if(!['mock','ollama'].includes(process.env.LLM_MODE||'mock'))throw new Error('Unsupported LLM_MODE');
const token=process.env.DEMO_AGENT_TOKEN;
if(!token)throw new Error('DEMO_AGENT_TOKEN required (at least 24 characters)');
const pool=new Pool({connectionString:process.env.DATABASE_URL,max:5});
const app=buildApp(new PostgresOperationsStore(pool),demoAuthenticator([{userId:'agent-a',agencyId:'agency-a',token}]),new ApprovalService(pool),()=>process.env.LLM_MODE==='ollama'?new OllamaPlanner(process.env.OLLAMA_MODEL||'qwen3:4b'):new DemoPlanner());
await registerDemoWeb(app,token,Number(process.env.PORT||3000));
app.addHook('onClose',async()=>{await pool.end();});
await app.listen({host:'127.0.0.1',port:Number(process.env.PORT||3000)});
for(const signal of ['SIGINT','SIGTERM'] as const)process.once(signal,()=>{void app.close();});
