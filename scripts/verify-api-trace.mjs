import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
if(!process.env.DEMO_AGENT_TOKEN)throw Error('Demo token required');
const headers={authorization:'Bearer '+process.env.DEMO_AGENT_TOKEN,'content-type':'application/json'};
const started=Date.now();
const response=await fetch('http://127.0.0.1:3000/groups/group-a/reminder-runs',{method:'POST',headers,body:JSON.stringify({request:'Find unpaid bookings with missing documents, check both contract deadlines, and prepare a reminder for human review.'}),signal:AbortSignal.timeout(120000)});
assert.equal(response.status,200,'Reminder API request failed');
const run=await response.json();
assert.equal(run.status,'pending_review');assert.equal(run.deliveryEnabled,false);
const retrieved=await fetch('http://127.0.0.1:3000/groups/group-a/runs/'+run.traceId+'/trace',{headers,signal:AbortSignal.timeout(10000)});
assert.equal(retrieved.status,200);
const trace=await retrieved.json();
assert.equal(trace.traceId,run.runId);assert.equal(trace.delivery,null);
for(const type of ['user_request','permission_check','model_decision','tool_selected','tool_result','final_answer'])assert.ok(trace.events.some(e=>e.type===type),type);
assert.equal(trace.events.filter(e=>e.type==='model_decision').length,3);
assert.ok(trace.events.every((e,i)=>i===0||BigInt(e.sequence)>BigInt(trace.events[i-1].sequence)));
const denied=await fetch('http://127.0.0.1:3000/groups/group-b/runs/'+run.traceId+'/trace',{headers});
assert.equal(denied.status,404);
await mkdir('docs/evals',{recursive:true});
await writeFile('docs/evals/api-trace-example.json',JSON.stringify({verifiedAt:new Date().toISOString(),scope:'Actual loopback HTTP API and local PostgreSQL/semantic retrieval. Planner mode is recorded in run. No approval or delivery.',...trace},null,2)+'\n');
const report={verifiedAt:new Date().toISOString(),passed:true,traceId:run.traceId,plannerMode:run.plannerMode,eventCount:trace.events.length,durationMs:Date.now()-started,deliveryEnabled:false,approved:false,modelUsage:trace.run.model_usage,evidence:'api-trace-example.json'};
await writeFile('docs/evals/api-trace-verification.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
